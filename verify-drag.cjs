const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
let pending,scrolled=0,focused=0;
const handlers={};
const title={addEventListener:(k,f)=>handlers[k]=f,focus:()=>focused++,setSelectionRange:()=>{},value:'a',setAttribute:()=>{}};
const context={document:{activeElement:null,getElementById:()=>({})},window:{scrollBy:o=>scrolled+=o.top},setTimeout:f=>(pending=f,1),clearTimeout:()=>pending=null,cancelAnimationFrame:()=>{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('drag.js','utf8'),context);
context.bindDrag(title,{},'food',{});
const touch=y=>({identifier:1,clientX:20,clientY:y});
let prevented=0;
const event=y=>({touches:[touch(y)],changedTouches:[touch(y)],preventDefault:()=>prevented++});
handlers.touchstart(event(100));assert.ok(pending);
handlers.touchend(event(100));assert.equal(focused,1);
handlers.touchstart(event(100));handlers.touchmove(event(70));
assert.equal(scrolled,30);assert.equal(pending,null);
handlers.touchend(event(70));assert.equal(focused,1);
handlers.touchstart(event(100));handlers.touchcancel();assert.equal(pending,null);
context.document.activeElement=title;
const before=prevented;handlers.touchstart(event(100));assert.equal(prevented,before);
console.log('PASS: tap editing, swipe scrolling, cancellation, native editing gestures');
