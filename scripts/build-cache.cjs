// Regenerate after adding/removing a public runtime asset.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../public');
const assets=['./','./index.html','./moving/','./beijing/','./shared/precache.js'];
function collect(directory=''){
 for(const entry of fs.readdirSync(path.join(root,directory),{withFileTypes:true})){
  const file=path.posix.join(directory,entry.name);
  if(entry.isDirectory())collect(file);
  else if(/\.(?:js|css|svg|webp|png)$/.test(file)&&!['sw.js','shared/precache.js'].includes(file))assets.push('./'+file);
 }
}
collect();
fs.writeFileSync(path.join(root,'shared/precache.js'),'// Generated by npm run cache.\nconst PRECACHE_URLS='+JSON.stringify(assets,null,2)+';\n');
console.log(`Prepared ${assets.length} offline URLs`);
